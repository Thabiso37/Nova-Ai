\set ON_ERROR_STOP on

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'novaai_inventory_owner') THEN
    CREATE ROLE novaai_inventory_owner NOLOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT NOREPLICATION NOBYPASSRLS;
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'novaai_privileged_probe') THEN
    CREATE ROLE novaai_privileged_probe NOLOGIN;
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'novaai_inventory_inspector') THEN
    CREATE ROLE novaai_inventory_inspector LOGIN PASSWORD 'local-test-only' NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT NOREPLICATION NOBYPASSRLS;
  END IF;
END $$;

REVOKE ALL ON DATABASE inventory_test FROM PUBLIC;
GRANT CONNECT ON DATABASE inventory_test TO novaai_inventory_inspector;
REVOKE TEMPORARY, CREATE ON DATABASE inventory_test FROM novaai_inventory_inspector;

CREATE SCHEMA IF NOT EXISTS novaai_app AUTHORIZATION novaai_inventory_owner;
CREATE SCHEMA IF NOT EXISTS novaai_private AUTHORIZATION novaai_inventory_owner;
GRANT USAGE ON SCHEMA novaai_app, novaai_private TO novaai_inventory_inspector;
REVOKE CREATE ON SCHEMA novaai_app, novaai_private FROM novaai_inventory_inspector;

SET ROLE novaai_inventory_owner;

CREATE TABLE novaai_app.customers (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email text NOT NULL UNIQUE,
  synthetic_canary text NOT NULL
);
CREATE TABLE novaai_app.rls_disabled_probe (payload text NOT NULL);
CREATE TABLE novaai_app.inheritance_probe (protected_value text NOT NULL);
CREATE TABLE novaai_app.sellers (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  phone text,
  synthetic_canary text NOT NULL
);
CREATE DOMAIN novaai_app.positive_amount AS numeric(12,2)
  CONSTRAINT positive_amount_check CHECK (VALUE > 0);
CREATE TYPE novaai_app.order_state AS ENUM ('pending','paid','cancelled');
CREATE TABLE novaai_app.orders (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id bigint NOT NULL REFERENCES novaai_app.customers(id),
  amount novaai_app.positive_amount NOT NULL,
  state novaai_app.order_state NOT NULL DEFAULT 'pending'
);
CREATE TABLE novaai_app.partitioned_events (
  event_id bigint NOT NULL,
  occurred_at timestamptz NOT NULL,
  note text
) PARTITION BY RANGE (occurred_at);
CREATE TABLE novaai_app.partitioned_events_2026
  PARTITION OF novaai_app.partitioned_events
  FOR VALUES FROM ('2026-01-01') TO ('2027-01-01');
CREATE INDEX partitioned_events_note_idx ON novaai_app.partitioned_events (note);

CREATE VIEW novaai_app.customer_view AS
  SELECT id, email FROM novaai_app.customers;
CREATE MATERIALIZED VIEW novaai_app.order_summary AS
  SELECT state, count(*) AS order_count FROM novaai_app.orders GROUP BY state;

CREATE FUNCTION novaai_app.customer_count() RETURNS bigint
LANGUAGE sql STABLE SECURITY INVOKER
AS $$ SELECT count(*) FROM novaai_app.customers $$;
CREATE FUNCTION novaai_app.definer_probe() RETURNS bigint
LANGUAGE sql STABLE SECURITY DEFINER
SET search_path = pg_catalog
AS $$ SELECT count(*) FROM novaai_app.customers $$;

CREATE TABLE novaai_app.audit_log (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event text NOT NULL
);
CREATE FUNCTION novaai_app.audit_trigger_fn() RETURNS trigger
LANGUAGE plpgsql
AS $$ BEGIN INSERT INTO novaai_app.audit_log(event) VALUES (TG_OP); RETURN NEW; END $$;
CREATE TRIGGER customers_audit AFTER INSERT ON novaai_app.customers
FOR EACH ROW EXECUTE FUNCTION novaai_app.audit_trigger_fn();

