#!/usr/bin/env bash
set -Eeuo pipefail
umask 077
WORK="$(mktemp -d)"
PRIMARY="$WORK/primary"; STANDBY="$WORK/standby"
PP=55432; SP=55433
RP="$(od -An -N24 -tx1 /dev/urandom | tr -d ' \n')"
EP="$(od -An -N24 -tx1 /dev/urandom | tr -d ' \n')"
export PGUSER=postgres PGHOST=127.0.0.1 PGDATABASE=postgres PGPORT="$PP"
cleanup(){ pg_ctl -D "$STANDBY" -m immediate stop >/dev/null 2>&1 || true; pg_ctl -D "$PRIMARY" -m immediate stop >/dev/null 2>&1 || true; rm -rf "$WORK"; }
trap cleanup EXIT INT TERM
if [[ "$(id -u)" -eq 0 ]]; then chown postgres:postgres "$WORK"; aspg(){ runuser -u postgres -- "$@"; }; else aspg(){ "$@"; }; fi
aspg mkdir -p "$PRIMARY" "$STANDBY"
aspg initdb -D "$PRIMARY" --auth-local=trust --auth-host=trust >/dev/null
cat >> "$PRIMARY/postgresql.conf" <<EOF
listen_addresses='*'
port=$PP
wal_level=replica
max_wal_senders=8
max_replication_slots=4
hot_standby=on
EOF
cat >> "$PRIMARY/pg_hba.conf" <<'EOF'
host all all 127.0.0.1/32 trust
host replication repl 127.0.0.1/32 trust
host all all 0.0.0.0/0 scram-sha-256
host replication repl 0.0.0.0/0 scram-sha-256
EOF
aspg pg_ctl -D "$PRIMARY" -l "$WORK/primary.log" -w start >/dev/null
psql -X -v ON_ERROR_STOP=1 <<SQL
CREATE ROLE repl LOGIN REPLICATION PASSWORD '$RP';
CREATE ROLE safe_export LOGIN PASSWORD '$EP';
ALTER ROLE safe_export SET default_transaction_read_only=on;
REVOKE TEMPORARY ON DATABASE postgres FROM PUBLIC;
REVOKE EXECUTE ON FUNCTION pg_catalog.lo_create(oid),pg_catalog.lo_from_bytea(oid,bytea),pg_catalog.lo_put(oid,bigint,bytea),pg_catalog.lo_unlink(oid),pg_catalog.lo_import(text),pg_catalog.lo_import(text,oid),pg_catalog.lo_export(oid,text),pg_catalog.lo_open(oid,integer),pg_catalog.lowrite(integer,bytea),pg_catalog.lo_truncate(integer,integer),pg_catalog.lo_truncate64(integer,bigint) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION pg_catalog.lo_create(oid),pg_catalog.lo_put(oid,bigint,bytea),pg_catalog.lo_unlink(oid) TO safe_export;
SELECT pg_catalog.lo_create(900001);
SELECT pg_catalog.lo_put(900001,0,convert_to('HOT_STANDBY_LO_DATA_MUST_NOT_EXPORT','UTF8'));
CREATE SCHEMA private;
CREATE SCHEMA storage;
CREATE SCHEMA supabase_migrations;
CREATE TABLE supabase_migrations.schema_migrations(version text PRIMARY KEY);
INSERT INTO supabase_migrations.schema_migrations VALUES('202611090001');
CREATE TABLE storage.buckets(id text PRIMARY KEY,name text NOT NULL,public boolean NOT NULL DEFAULT false,file_size_limit bigint,allowed_mime_types text[]);
CREATE TABLE storage.objects(id uuid PRIMARY KEY,bucket_id text,name text);
ALTER TABLE storage.objects ENABLE ROW LEVEL SECURITY;
CREATE POLICY export_storage_objects_read ON storage.objects FOR SELECT TO safe_export USING (true);
INSERT INTO storage.buckets(id,name) VALUES('fixture','Fixture bucket');
CREATE TABLE public.products(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,name text NOT NULL);
CREATE TABLE public."Products"(id bigint PRIMARY KEY,label text);
CREATE TABLE public.partitioned_parent(id int,payload text) PARTITION BY RANGE(id);
CREATE TABLE public.partitioned_child PARTITION OF public.partitioned_parent FOR VALUES FROM(0) TO(100);
CREATE VIEW public.export_view AS SELECT id,name FROM public.products;
CREATE MATERIALIZED VIEW public.export_matview AS SELECT count(*) AS product_count FROM public.products;
CREATE SEQUENCE public.export_sequence;
GRANT USAGE ON SEQUENCE public.export_sequence TO safe_export;
CREATE FUNCTION public.export_helper() RETURNS int LANGUAGE sql IMMUTABLE AS 'SELECT 17';
CREATE FUNCTION public.export_trigger_fn() RETURNS trigger LANGUAGE plpgsql AS 'BEGIN NEW.name:=upper(NEW.name); RETURN NEW; END';
CREATE TRIGGER export_products_trigger BEFORE INSERT ON public.products FOR EACH ROW EXECUTE FUNCTION public.export_trigger_fn();
CREATE FUNCTION public.standby_secdef_write() RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path=pg_catalog,public AS 'BEGIN INSERT INTO public.products(name) VALUES (''SECDEF_STANDBY_WRITE''); END';
GRANT EXECUTE ON FUNCTION public.standby_secdef_write() TO safe_export;
CREATE TABLE public.export_marker(id int PRIMARY KEY,payload text);
INSERT INTO public.export_marker VALUES(1,'HOT_STANDBY_APPLICATION_ROW_MUST_NOT_EXPORT');
GRANT USAGE ON SCHEMA public,private,storage,supabase_migrations TO safe_export;
GRANT SELECT ON ALL TABLES IN SCHEMA public,private,storage,supabase_migrations TO safe_export;
REVOKE EXECUTE ON ALL FUNCTIONS IN SCHEMA public FROM PUBLIC;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT SELECT ON TABLES TO safe_export;
SQL
psql -X -v ON_ERROR_STOP=1 <<'SQL'
CREATE EXTENSION file_fdw;
CREATE SERVER export_file_server FOREIGN DATA WRAPPER file_fdw;
CREATE FOREIGN TABLE public.export_foreign_table(line text) SERVER export_file_server OPTIONS(filename '/dev/null',format 'text');
GRANT SELECT ON public.export_foreign_table TO safe_export;
GRANT SELECT ON storage.buckets TO safe_export;
REVOKE EXECUTE ON ALL FUNCTIONS IN SCHEMA public FROM PUBLIC;
SQL
PGPASSWORD="$RP" aspg pg_basebackup -h 127.0.0.1 -p "$PP" -U repl -D "$STANDBY" -Fp -Xs -P -R
cat >> "$STANDBY/postgresql.conf" <<EOF
listen_addresses='*'
port=$SP
hot_standby=on
EOF
aspg pg_ctl -D "$STANDBY" -l "$WORK/standby.log" -w start >/dev/null
export PGPORT="$SP"
SOURCE_LSN="$(PGUSER=postgres PGPASSWORD= PGPORT="$PP" psql -X -Atqc "SELECT pg_current_wal_lsn()")"
for _ in $(seq 1 60); do psql -X -Atqc 'SELECT pg_is_in_recovery()' 2>/dev/null | grep -qx t && break; sleep 1; done
psql -X -Atqc "SELECT pg_is_in_recovery() AND current_setting('transaction_read_only')='on' AND current_setting('in_hot_standby')='on'" | grep -qx t
for _ in $(seq 1 60); do psql -X -Atqc "SELECT pg_last_wal_replay_lsn() >= '$SOURCE_LSN'::pg_lsn" | grep -qx t && break; sleep 1; done
psql -X -Atqc "SELECT pg_last_wal_replay_lsn() >= '$SOURCE_LSN'::pg_lsn" | grep -qx t
printf '%s\\n' "$SOURCE_LSN" > "$WORK/source-primary-lsn"
psql -X -Atqc "SELECT pg_last_wal_replay_lsn()" > "$WORK/source-standby-replay-lsn"
echo "PASS: genuine recovery mode and independent read-only settings."
export PGUSER=safe_export PGPASSWORD="$EP"
IDENTITY="$(psql -X -Atqc "SELECT current_user || ':' || current_setting('transaction_read_only')")"
[[ "$IDENTITY" == "safe_export:on" ]] || { echo "Unexpected restricted-login identity/settings: $IDENTITY" >&2; exit 1; }
if psql -X -v ON_ERROR_STOP=1 -c 'SET transaction_read_only=off' >"$WORK/setoff" 2>&1; then echo "ERROR: standby allowed transaction_read_only=off" >&2; exit 1; fi
if ! grep -Eqi 'read.only transaction|cannot set transaction_read_only|during recovery' "$WORK/setoff"; then cat "$WORK/setoff" >&2; exit 1; fi
echo "PASS: standby rejected SET transaction_read_only=off."
expect_ro(){ label="$1"; shift; if "$@" >"$WORK/attempt" 2>&1; then echo "unexpected write success: $label" >&2; exit 1; fi; if ! grep -Eqi 'read.only transaction|recovery mode|cannot execute' "$WORK/attempt"; then cat "$WORK/attempt" >&2; exit 1; fi; echo "PASS: $label rejected"; }
expect_ro INSERT psql -X -v ON_ERROR_STOP=1 -c "INSERT INTO public.products(name) VALUES('blocked')"
expect_ro UPDATE psql -X -v ON_ERROR_STOP=1 -c "UPDATE public.products SET name='blocked' WHERE id=1"
expect_ro DELETE psql -X -v ON_ERROR_STOP=1 -c "DELETE FROM public.products WHERE id=1"
expect_ro TEMP psql -X -v ON_ERROR_STOP=1 -c "CREATE TEMP TABLE blocked(id int)"
expect_ro SEQUENCE psql -X -v ON_ERROR_STOP=1 -c "SELECT nextval('public.export_sequence')"
PGUSER=postgres PGPASSWORD= PGPORT="$PP" psql -X -v ON_ERROR_STOP=1 -c "REVOKE USAGE ON SEQUENCE public.export_sequence FROM safe_export"
if psql -X -v ON_ERROR_STOP=1 -c "SELECT lo_create(0)" >"$WORK/lo1" 2>&1; then exit 1; fi
grep -Eqi 'read.only transaction|recovery mode' "$WORK/lo1"
if psql -X -v ON_ERROR_STOP=1 -c "SELECT lo_put(900001,0,decode('02','hex'))" >"$WORK/lo2" 2>&1; then exit 1; fi
grep -Eqi 'read.only transaction|recovery mode|cannot execute' "$WORK/lo2"
if psql -X -v ON_ERROR_STOP=1 -c "SELECT lo_unlink(900001)" >"$WORK/lo3" 2>&1; then exit 1; fi
grep -Eqi 'read.only transaction|recovery mode|cannot execute' "$WORK/lo3"
echo "PASS: large-object creation, modification and deletion rejected."
if psql -X -v ON_ERROR_STOP=1 -c "SELECT public.standby_secdef_write()" >"$WORK/secdef" 2>&1; then exit 1; fi
grep -Eqi 'read.only transaction|recovery mode' "$WORK/secdef"
echo "PASS: SECURITY DEFINER local write rejected."
PGUSER=postgres PGPASSWORD= PGPORT="$PP" psql -X -v ON_ERROR_STOP=1 -c "REVOKE EXECUTE ON FUNCTION public.standby_secdef_write() FROM safe_export"
for _ in $(seq 1 60); do psql -X -Atqc "SELECT has_function_privilege(current_user,'public.standby_secdef_write()','EXECUTE')" 2>/dev/null | grep -qx f && break; sleep 1; done
psql -X -v ON_ERROR_STOP=1 -f scripts/schema-export/assert-read-only-role.sql
echo "PASS: production read-only preflight accepted the restricted login on standby."
psql -X -v ON_ERROR_STOP=1 <<'SQL'
BEGIN READ ONLY;
LOCK TABLE public.products IN ACCESS SHARE MODE;
LOCK TABLE public."Products" IN ACCESS SHARE MODE;
LOCK TABLE public.partitioned_parent IN ACCESS SHARE MODE;
LOCK TABLE public.partitioned_child IN ACCESS SHARE MODE;
LOCK TABLE public.export_view IN ACCESS SHARE MODE;
COMMIT;
SQL
echo "PASS: ACCESS SHARE locks on relation kinds used by pg_dump."
URL="postgresql://safe_export:$EP@127.0.0.1:$SP/postgres?sslmode=disable"
psql -X -Atqc "SELECT max(version) FROM supabase_migrations.schema_migrations" >"$WORK/watermark.before"
psql -X -Atqc "SELECT pg_last_wal_replay_lsn()" >"$WORK/replay.before"
pg_dump --version | grep -F '17.11'
pg_dump --schema-only --no-owner --no-privileges --schema=public --schema=private --file="$WORK/direct.sql" "$URL"
for pat in 'CREATE TABLE public\.products' 'CREATE TABLE public\."Products"' 'CREATE VIEW public\.export_view' 'CREATE MATERIALIZED VIEW public\.export_matview' 'CREATE FUNCTION public\.export_helper' 'CREATE TRIGGER export_products_trigger' 'CREATE SEQUENCE public\.export_sequence' 'CREATE FOREIGN TABLE public\.export_foreign_table'; do grep -Eq "$pat" "$WORK/direct.sql" || { echo "missing schema object: $pat" >&2; exit 1; }; done
! grep -Eiq 'HOT_STANDBY_APPLICATION_ROW_MUST_NOT_EXPORT|HOT_STANDBY_LO_DATA_MUST_NOT_EXPORT|^[[:space:]]*(COPY[[:space:]]|INSERT[[:space:]]+INTO)' "$WORK/direct.sql"
echo "PASS: PostgreSQL 17.11 pg_dump schema-only and schema object/data checks."
supabase --version | grep -F '2.122.1'
NETWORK_ID="$(docker inspect "$HOSTNAME" --format '{{range .NetworkSettings.Networks}}{{.NetworkID}}{{end}}')"
JOB_IP="$(docker inspect "$HOSTNAME" --format '{{range .NetworkSettings.Networks}}{{.IPAddress}}{{end}}')"
[[ -n "$NETWORK_ID" && -n "$JOB_IP" ]]
CLI_URL="postgresql://safe_export:$EP@$JOB_IP:$SP/postgres?sslmode=disable"
if supabase --network-id "$NETWORK_ID" db dump --db-url "$CLI_URL" --schema public,private --file "$WORK/supabase.sql" >"$WORK/supabase-cli.log" 2>&1; then
  echo "UNEXPECTED: pinned Supabase CLI succeeded with restricted login; inspect any behavior change." 
  grep -Eq 'CREATE TABLE public\.products' "$WORK/supabase.sql"
  grep -Eq 'CREATE TABLE public\."Products"' "$WORK/supabase.sql"
  ! grep -Eiq 'HOT_STANDBY_APPLICATION_ROW_MUST_NOT_EXPORT|HOT_STANDBY_LO_DATA_MUST_NOT_EXPORT|^[[:space:]]*(COPY[[:space:]]|INSERT[[:space:]]+INTO)' "$WORK/supabase.sql"
  cp "$WORK/supabase.sql" "$WORK/schema.sql"
else
  if grep -Fq 'permission denied to set role "postgres"' "$WORK/supabase-cli.log"; then
    echo "CONFIRMED CLI INCOMPATIBILITY: supabase db dump attempts SET ROLE postgres, which the restricted export login must not be allowed to assume."
    cp "$WORK/direct.sql" "$WORK/schema.sql"
  else
    cat "$WORK/supabase-cli.log" >&2
    exit 1
  fi
fi
psql -X -f scripts/schema-export/export-manifests.sql -o "$WORK/manifests.json"
jq -e '.manifest_version == 2 and (.policies | any(.name == "export_storage_objects_read")) and (.functions | any(.name == "export_helper")) and (.triggers | any(.name == "export_products_trigger")) and (.indexes | length > 0) and (.constraints | length > 0)' "$WORK/manifests.json" >/dev/null
bash scripts/schema-export/validate-export.sh "$WORK"
psql -X -Atqc "SELECT max(version) FROM supabase_migrations.schema_migrations" >"$WORK/watermark.after"
psql -X -Atqc "SELECT pg_last_wal_replay_lsn()" >"$WORK/replay.after"
cmp "$WORK/watermark.before" "$WORK/watermark.after"
grep -q '202611090001' "$WORK/manifests.json"
! grep -Fq 'HOT_STANDBY_LO_DATA_MUST_NOT_EXPORT' "$WORK/manifests.json"
printf 'Migration watermark: before=%s after=%s\\n' "$(cat "$WORK/watermark.before")" "$(cat "$WORK/watermark.after")"
printf 'WAL replay freshness: primary_lsn=%s standby_replay_start=%s standby_replay_end=%s\\n' "$SOURCE_LSN" "$(cat "$WORK/replay.before")" "$(cat "$WORK/replay.after")"
echo "PASS: stable watermark bracket and replay LSN captured."
PGUSER=postgres PGPASSWORD= PGPORT="$PP" psql -X -v ON_ERROR_STOP=1 -c "ALTER TABLE public.products ADD COLUMN watermark_probe text; UPDATE supabase_migrations.schema_migrations SET version='202611090002'"
for _ in $(seq 1 60); do psql -X -Atqc "SELECT max(version) FROM supabase_migrations.schema_migrations" 2>/dev/null | grep -qx 202611090002 && break; sleep 1; done
psql -X -Atqc "SELECT max(version) FROM supabase_migrations.schema_migrations" | grep -qx 202611090002
if cmp -s "$WORK/watermark.before" <(psql -X -Atqc "SELECT max(version) FROM supabase_migrations.schema_migrations"); then echo "ERROR: watermark drift was not detected" >&2; exit 1; fi
! grep -q watermark_probe "$WORK/direct.sql"
echo "PASS: advancing WAL changes watermark; separate schema/manifest drift is detectable."
echo "Genuine PostgreSQL 17.11 hot-standby tests passed."
