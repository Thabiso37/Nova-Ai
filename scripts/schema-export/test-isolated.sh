#!/usr/bin/env bash
set -Eeuo pipefail
export PGHOST="${PGHOST:-postgres}" PGPORT="${PGPORT:-5432}" PGUSER="${PGUSER:-postgres}" PGPASSWORD="${PGPASSWORD:-postgres}" PGDATABASE="${PGDATABASE:-postgres}"
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
TMP="$(mktemp -d)"
TEST_EXPORT_PASSWORD="$(od -An -N24 -tx1 /dev/urandom | tr -d ' \n')"
cleanup(){ rm -rf "$TMP"; }
trap cleanup EXIT

psql -X -v ON_ERROR_STOP=1 -v export_password="$TEST_EXPORT_PASSWORD" <<'SQL'
CREATE ROLE safe_export LOGIN PASSWORD :'export_password';
ALTER ROLE safe_export SET default_transaction_read_only = on;
CREATE ROLE inherited_writer NOLOGIN;
CREATE ROLE member_export LOGIN;
CREATE ROLE direct_writer LOGIN;
CREATE ROLE sequence_writer LOGIN;
CREATE ROLE function_writer LOGIN;
CREATE ROLE function_owner LOGIN;
CREATE ROLE schema_writer LOGIN;
CREATE ROLE column_writer LOGIN;
CREATE ROLE temp_writer LOGIN;
CREATE ROLE anon NOLOGIN;
CREATE ROLE authenticated NOLOGIN;
REVOKE TEMPORARY ON DATABASE postgres FROM PUBLIC;
-- Isolate a safe baseline: remove PUBLIC execution only for the specific write-capable
-- large-object routines under test. The test later restores these grants in this disposable DB.
REVOKE EXECUTE ON FUNCTION
  pg_catalog.lo_create(oid),
  pg_catalog.lo_from_bytea(oid,bytea),
  pg_catalog.lo_put(oid,bigint,bytea),
  pg_catalog.lo_unlink(oid),
  pg_catalog.lo_import(text),
  pg_catalog.lo_import(text,oid),
  pg_catalog.lo_export(oid,text),
  pg_catalog.lo_open(oid,integer),
  pg_catalog.lowrite(integer,bytea),
  pg_catalog.lo_truncate(integer,integer),
  pg_catalog.lo_truncate64(integer,bigint)
FROM PUBLIC;
GRANT TEMPORARY ON DATABASE postgres TO temp_writer;
CREATE SCHEMA private;
CREATE SCHEMA storage;
CREATE TABLE public.products(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name text NOT NULL);
CREATE TABLE public."Products"(id bigint PRIMARY KEY, label text);
CREATE TABLE private.internal_config(id integer PRIMARY KEY, value text);
CREATE TABLE public.no_select_manifest_fixture(id bigint PRIMARY KEY, label text NOT NULL, created_at timestamptz NOT NULL DEFAULT now());
ALTER TABLE public.no_select_manifest_fixture ENABLE ROW LEVEL SECURITY;
CREATE POLICY no_select_fixture_read ON public.no_select_manifest_fixture FOR SELECT TO safe_export USING (true);
CREATE TABLE storage.buckets(id text PRIMARY KEY, name text NOT NULL, public boolean NOT NULL DEFAULT false, file_size_limit bigint, allowed_mime_types text[]);
CREATE TABLE storage.objects(id uuid PRIMARY KEY, bucket_id text, name text);
CREATE SEQUENCE public.synthetic_seq;
CREATE FUNCTION public.safe_constant() RETURNS integer LANGUAGE sql IMMUTABLE AS 'SELECT 7';
CREATE FUNCTION public.owner_only() RETURNS integer LANGUAGE sql IMMUTABLE AS 'SELECT 1';
REVOKE ALL ON FUNCTION public.owner_only() FROM PUBLIC;
ALTER FUNCTION public.owner_only() OWNER TO function_owner;
REVOKE ALL ON FUNCTION public.safe_constant() FROM PUBLIC;
CREATE FUNCTION public.public_callable() RETURNS integer LANGUAGE sql IMMUTABLE AS 'SELECT 9';
CREATE FUNCTION public.unsafe_change() RETURNS void LANGUAGE plpgsql VOLATILE AS $function$ BEGIN INSERT INTO public.products(name) VALUES ('forbidden'); END $function$;
REVOKE ALL ON FUNCTION public.unsafe_change() FROM PUBLIC;
ALTER TABLE public.products ENABLE ROW LEVEL SECURITY;
CREATE POLICY products_read ON public.products FOR SELECT TO safe_export USING (true);
ALTER TABLE storage.objects ENABLE ROW LEVEL SECURITY;
CREATE POLICY storage_objects_read ON storage.objects FOR SELECT TO safe_export USING (true);
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT SELECT ON TABLES TO safe_export;
INSERT INTO storage.buckets(id,name) VALUES ('synthetic','Synthetic bucket');
INSERT INTO public.products(name) VALUES ('SYNTHETIC_DATA_MUST_NOT_EXPORT');
GRANT USAGE ON SCHEMA public,private,storage TO safe_export;
GRANT SELECT ON public.products,public."Products",private.internal_config,storage.buckets TO safe_export;
-- safe_export deliberately has no SELECT on no_select_manifest_fixture or storage.objects.
GRANT inherited_writer TO member_export;
GRANT SELECT ON public.products TO member_export;
GRANT INSERT ON public.products TO inherited_writer;
GRANT USAGE ON SCHEMA public TO inherited_writer;
GRANT INSERT ON public.products TO direct_writer;
GRANT UPDATE (name) ON public.products TO column_writer;
GRANT SELECT ON public.products TO PUBLIC;
GRANT SELECT ON public.products TO anon, authenticated;
GRANT USAGE ON SCHEMA public TO direct_writer;
GRANT USAGE,UPDATE ON SEQUENCE public.synthetic_seq TO sequence_writer;
GRANT EXECUTE ON FUNCTION public.unsafe_change() TO function_writer;
GRANT CREATE ON SCHEMA public TO schema_writer;
SQL

if psql -X -v ON_ERROR_STOP=1 -Atqc "SELECT has_table_privilege('safe_export', 'public.no_select_manifest_fixture', 'SELECT')" | grep -qx t; then echo "ERROR: fixture unexpectedly grants SELECT to safe_export" >&2; exit 1; fi
printf 'SET ROLE safe_export;\n\\o %s\n' "$TMP/manifests.json" > "$TMP/export-manifests-as-role.sql"
cat "$ROOT/scripts/schema-export/export-manifests.sql" >> "$TMP/export-manifests-as-role.sql"
psql -X -v ON_ERROR_STOP=1 -f "$TMP/export-manifests-as-role.sql"
jq -e '[.tables_and_columns[] | select(.schema == "public" and .table == "no_select_manifest_fixture") | .column] | sort == ["created_at","id","label"]' "$TMP/manifests.json" >/dev/null || { echo "ERROR: catalog manifest omitted columns from a table without SELECT" >&2; exit 1; }
jq -e '[.tables_and_columns[] | select(.schema == "public" and (.table == "products" or .table == "Products")) | .table] | unique == ["Products","products"]' "$TMP/manifests.json" >/dev/null
jq -e '.product_case_check.lower_exists and .product_case_check.upper_exists and .product_case_check.distinct' "$TMP/manifests.json" >/dev/null
jq -e '.policies | any(.name == "products_read") and any(.name == "storage_objects_read")' "$TMP/manifests.json" >/dev/null
jq -e '.default_privileges | length > 0' "$TMP/manifests.json" >/dev/null
jq -e '.schema_grants | any(.grantee == "schema_writer" and .privilege == "CREATE")' "$TMP/manifests.json" >/dev/null
jq -e '.table_grants | any(.grantee == "PUBLIC" and .table == "products" and .privilege == "SELECT")' "$TMP/manifests.json" >/dev/null
jq -e '.table_grants | any(.grantee == "anon" and .table == "products" and .privilege == "SELECT") and any(.grantee == "authenticated" and .table == "products" and .privilege == "SELECT")' "$TMP/manifests.json" >/dev/null
jq -e '.column_grants | any(.grantee == "column_writer" and .table == "products" and .column == "name" and .privilege == "UPDATE")' "$TMP/manifests.json" >/dev/null
jq -e '.sequence_grants | any(.grantee == "sequence_writer" and .privilege == "UPDATE")' "$TMP/manifests.json" >/dev/null
