#!/usr/bin/env bash
set -Eeuo pipefail
export PGHOST="${PGHOST:-postgres}" PGPORT="${PGPORT:-5432}" PGUSER="${PGUSER:-postgres}" PGPASSWORD="${PGPASSWORD:-postgres}" PGDATABASE="${PGDATABASE:-postgres}"
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
TMP="$(mktemp -d)"
TEST_EXPORT_PASSWORD="$(od -An -N24 -tx1 /dev/urandom | tr -d ' \n')"
cleanup(){ rm -rf "$TMP"; }
trap cleanup EXIT

psql -X -v ON_ERROR_STOP=1 -v export_password="$TEST_EXPORT_PASSWORD" <<'SQL'
CREATE ROLE safe_export LOGIN PASSWORD :'export_password';
ALTER ROLE safe_export SET default_transaction_read_only = on;
CREATE ROLE inherited_writer NOLOGIN;
CREATE ROLE member_export LOGIN;
CREATE ROLE direct_writer LOGIN;
CREATE ROLE sequence_writer LOGIN;
CREATE ROLE function_writer LOGIN;
CREATE ROLE schema_writer LOGIN;
CREATE ROLE column_writer LOGIN;
CREATE ROLE temp_writer LOGIN;
CREATE ROLE anon NOLOGIN;
CREATE ROLE authenticated NOLOGIN;
REVOKE TEMPORARY ON DATABASE postgres FROM PUBLIC;
GRANT TEMPORARY ON DATABASE postgres TO temp_writer;
CREATE SCHEMA private;
CREATE SCHEMA storage;
CREATE TABLE public.products(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name text NOT NULL);
CREATE TABLE public."Products"(id bigint PRIMARY KEY, label text);
CREATE TABLE private.internal_config(id integer PRIMARY KEY, value text);
CREATE TABLE public.no_select_manifest_fixture(id bigint PRIMARY KEY, label text NOT NULL, created_at timestamptz NOT NULL DEFAULT now());
ALTER TABLE public.no_select_manifest_fixture ENABLE ROW LEVEL SECURITY;
CREATE POLICY no_select_fixture_read ON public.no_select_manifest_fixture FOR SELECT TO safe_export USING (true);
CREATE TABLE storage.buckets(id text PRIMARY KEY, name text NOT NULL, public boolean NOT NULL DEFAULT false, file_size_limit bigint, allowed_mime_types text[]);
CREATE TABLE storage.objects(id uuid PRIMARY KEY, bucket_id text, name text);
CREATE SEQUENCE public.synthetic_seq;
CREATE FUNCTION public.safe_constant() RETURNS integer LANGUAGE sql IMMUTABLE AS 'SELECT 7';
REVOKE ALL ON FUNCTION public.safe_constant() FROM PUBLIC;
CREATE FUNCTION public.public_callable() RETURNS integer LANGUAGE sql IMMUTABLE AS 'SELECT 9';
CREATE FUNCTION public.unsafe_change() RETURNS void LANGUAGE plpgsql VOLATILE AS $function$ BEGIN INSERT INTO public.products(name) VALUES ('forbidden'); END $function$;
REVOKE ALL ON FUNCTION public.unsafe_change() FROM PUBLIC;
ALTER TABLE public.products ENABLE ROW LEVEL SECURITY;
CREATE POLICY products_read ON public.products FOR SELECT TO safe_export USING (true);
ALTER TABLE storage.objects ENABLE ROW LEVEL SECURITY;
CREATE POLICY storage_objects_read ON storage.objects FOR SELECT TO safe_export USING (true);
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT SELECT ON TABLES TO safe_export;
INSERT INTO storage.buckets(id,name) VALUES ('synthetic','Synthetic bucket');
INSERT INTO public.products(name) VALUES ('SYNTHETIC_DATA_MUST_NOT_EXPORT');
GRANT USAGE ON SCHEMA public,private,storage TO safe_export;
GRANT SELECT ON public.products,public."Products",private.internal_config,storage.buckets TO safe_export;
-- safe_export deliberately has no SELECT on no_select_manifest_fixture or storage.objects.
GRANT inherited_writer TO member_export;
GRANT SELECT ON public.products TO member_export;
GRANT INSERT ON public.products TO inherited_writer;
GRANT USAGE ON SCHEMA public TO inherited_writer;
GRANT INSERT ON public.products TO direct_writer;
GRANT UPDATE (name) ON public.products TO column_writer;
GRANT SELECT ON public.products TO PUBLIC;
GRANT SELECT ON public.products TO anon, authenticated;
GRANT USAGE ON SCHEMA public TO direct_writer;
GRANT USAGE,UPDATE ON SEQUENCE public.synthetic_seq TO sequence_writer;
GRANT EXECUTE ON FUNCTION public.unsafe_change() TO function_writer;
GRANT CREATE ON SCHEMA public TO schema_writer;
SQL

if psql -X -v ON_ERROR_STOP=1 -Atqc "SELECT has_table_privilege('safe_export', 'public.no_select_manifest_fixture', 'SELECT')" | grep -qx t; then echo "ERROR: fixture unexpectedly grants SELECT to safe_export" >&2; exit 1; fi
printf 'SET ROLE safe_export;\n\\o %s\n' "$TMP/manifests.json" > "$TMP/export-manifests-as-role.sql"
cat "$ROOT/scripts/schema-export/export-manifests.sql" >> "$TMP/export-manifests-as-role.sql"
psql -X -v ON_ERROR_STOP=1 -f "$TMP/export-manifests-as-role.sql"
jq -e '[.tables_and_columns[] | select(.schema == "public" and .table == "no_select_manifest_fixture") | .column] | sort == ["created_at","id","label"]' "$TMP/manifests.json" >/dev/null || { echo "ERROR: catalog manifest omitted columns from a table without SELECT" >&2; exit 1; }
jq -e '[.tables_and_columns[] | select(.schema == "public" and (.table == "products" or .table == "Products")) | .table] | unique == ["Products","products"]' "$TMP/manifests.json" >/dev/null
jq -e '.product_case_check.lower_exists and .product_case_check.upper_exists and .product_case_check.distinct' "$TMP/manifests.json" >/dev/null
jq -e '.policies | any(.name == "products_read") and any(.name == "storage_objects_read")' "$TMP/manifests.json" >/dev/null
jq -e '.default_privileges | length > 0' "$TMP/manifests.json" >/dev/null
jq -e '.schema_grants | any(.grantee == "schema_writer" and .privilege == "CREATE")' "$TMP/manifests.json" >/dev/null
jq -e '.table_grants | any(.grantee == "PUBLIC" and .table == "products" and .privilege == "SELECT")' "$TMP/manifests.json" >/dev/null
jq -e '.table_grants | any(.grantee == "anon" and .table == "products" and .privilege == "SELECT") and any(.grantee == "authenticated" and .table == "products" and .privilege == "SELECT")' "$TMP/manifests.json" >/dev/null
jq -e '.column_grants | any(.grantee == "column_writer" and .table == "products" and .column == "name" and .privilege == "UPDATE")' "$TMP/manifests.json" >/dev/null
jq -e '.sequence_grants | any(.grantee == "sequence_writer" and .privilege == "UPDATE")' "$TMP/manifests.json" >/dev/null
jq -e '.function_grants | any(.grantee == "function_writer" and .function == "unsafe_change")' "$TMP/manifests.json" >/dev/null
jq -e '.function_grants | any(.grantee == "PUBLIC" and .function == "public_callable" and .privilege == "EXECUTE")' "$TMP/manifests.json" >/dev/null
jq -e '(.database_grants|type)=="array" and (.large_object_grants|type)=="array" and (.tablespace_grants|type)=="array" and (.parameter_grants|type)=="array"' "$TMP/manifests.json" >/dev/null
jq -e '.role_attributes | any(.role == "anon") and any(.role == "authenticated")' "$TMP/manifests.json" >/dev/null
psql -X -v ON_ERROR_STOP=1 -c 'REVOKE ALL ON FUNCTION public.public_callable() FROM PUBLIC' >/dev/null
jq -e '.sequences | any(.name == "synthetic_seq")' "$TMP/manifests.json" >/dev/null
jq -e '.functions | any(.name == "safe_constant") and any(.name == "unsafe_change")' "$TMP/manifests.json" >/dev/null
jq -e '.role_memberships | any(.member == "member_export" and .role == "inherited_writer")' "$TMP/manifests.json" >/dev/null
jq -e '.table_grants | any(.grantee == "direct_writer" and .privilege == "INSERT")' "$TMP/manifests.json" >/dev/null
PGPASSWORD="$TEST_EXPORT_PASSWORD" PGUSER=safe_export psql -X -v ON_ERROR_STOP=1 -Atqc "SELECT current_user" | grep -qx safe_export
PGPASSWORD="$TEST_EXPORT_PASSWORD" PGUSER=safe_export psql -X -v ON_ERROR_STOP=1 -Atqc "SELECT rolsuper=false AND rolbypassrls=false AND rolcreaterole=false AND rolcreatedb=false AND rolreplication=false AND rolcanlogin FROM pg_roles WHERE rolname=current_user" | grep -qx t
PGPASSWORD="$TEST_EXPORT_PASSWORD" PGUSER=safe_export psql -X -v ON_ERROR_STOP=1 -Atqc "SELECT count(*)=0 FROM pg_auth_members WHERE member=(SELECT oid FROM pg_roles WHERE rolname=current_user) OR roleid=(SELECT oid FROM pg_roles WHERE rolname=current_user)" | grep -qx t
PGPASSWORD="$TEST_EXPORT_PASSWORD" PGUSER=safe_export psql -X -v ON_ERROR_STOP=1 -Atqc "SELECT count(*)=0 FROM pg_class c JOIN pg_roles r ON r.oid=c.relowner WHERE r.rolname=current_user" | grep -qx t
PGPASSWORD="$TEST_EXPORT_PASSWORD" PGUSER=safe_export psql -X -v ON_ERROR_STOP=1 -Atqc "SHOW default_transaction_read_only" | grep -qx on
PGPASSWORD="$TEST_EXPORT_PASSWORD" PGUSER=safe_export psql -X -v ON_ERROR_STOP=1 -Atqc "SELECT NOT has_table_privilege(current_user,'public.no_select_manifest_fixture','SELECT') AND NOT has_table_privilege(current_user,'storage.objects','SELECT') AND has_table_privilege(current_user,'storage.buckets','SELECT')" | grep -qx t
PGPASSWORD="$TEST_EXPORT_PASSWORD" PGUSER=safe_export psql -X -v ON_ERROR_STOP=1 -f "$ROOT/scripts/schema-export/assert-read-only-role.sql" >/dev/null
if psql -X -v ON_ERROR_STOP=1 -c 'SET ROLE direct_writer' -f "$ROOT/scripts/schema-export/assert-read-only-role.sql" >/dev/null 2>&1; then echo "ERROR: direct writer passed" >&2; exit 1; fi
if psql -X -v ON_ERROR_STOP=1 -c 'SET ROLE member_export' -f "$ROOT/scripts/schema-export/assert-read-only-role.sql" >/dev/null 2>&1; then echo "ERROR: inherited writer passed" >&2; exit 1; fi
for bad_role in sequence_writer function_writer schema_writer column_writer temp_writer; do
  if psql -X -v ON_ERROR_STOP=1 -c "SET ROLE $bad_role" -f "$ROOT/scripts/schema-export/assert-read-only-role.sql" >/dev/null 2>&1; then echo "ERROR: $bad_role passed read-only preflight" >&2; exit 1; fi
done

# First attempt deliberately includes an RLS-enabled table for which safe_export has no SELECT.
set +e
PGPASSWORD="$TEST_EXPORT_PASSWORD" PGUSER=safe_export pg_dump -h "$PGHOST" -p "$PGPORT" -d "$PGDATABASE" --no-password --schema-only --schema=public --schema=private --strict-names --file="$TMP/schema-no-select.sql" 2>"$TMP/pg_dump-no-select.log"
NO_SELECT_DUMP_STATUS=$?
set -e
if [[ "$NO_SELECT_DUMP_STATUS" -eq 0 ]]; then
  echo "RESULT: restricted-login pg_dump succeeded without SELECT on public.no_select_manifest_fixture."
  cp "$TMP/schema-no-select.sql" "$TMP/schema.sql"
else
  if ! grep -Eiq 'permission denied.*(relation|table)|permission denied for table' "$TMP/pg_dump-no-select.log"; then
    cat "$TMP/pg_dump-no-select.log" >&2
    echo "ERROR: pg_dump failed for a reason other than the deliberate no-SELECT fixture." >&2
    exit 1
  fi
  echo "RESULT: pg_dump requires SELECT on the no-SELECT fixture; retrying with the minimum relation grant."
  cat "$TMP/pg_dump-no-select.log" >&2
  psql -X -v ON_ERROR_STOP=1 -c 'GRANT SELECT ON public.no_select_manifest_fixture TO safe_export' >/dev/null
  PGPASSWORD="$TEST_EXPORT_PASSWORD" PGUSER=safe_export pg_dump -h "$PGHOST" -p "$PGPORT" -d "$PGDATABASE" --no-password --schema-only --schema=public --schema=private --strict-names --file="$TMP/schema.sql"
fi
[[ -s "$TMP/schema.sql" ]]
if grep -Eiq '^[[:space:]]*(COPY[[:space:]]|INSERT[[:space:]]+INTO[[:space:]])' "$TMP/schema.sql"; then
  echo "ERROR: schema-only pg_dump emitted application table data." >&2
  exit 1
fi
! grep -Fq 'SYNTHETIC_DATA_MUST_NOT_EXPORT' "$TMP/schema.sql"
grep -Fq 'CREATE TABLE public.products' "$TMP/schema.sql"
grep -Fq 'CREATE TABLE public."Products"' "$TMP/schema.sql"
echo "RESULT: schema-only dump contains definitions and no fixture row data."

# Run the manifest as the same restricted login, including storage.buckets.
printf '\\o %s\n' "$TMP/login-manifests.json" > "$TMP/login-manifests.sql"
cat "$ROOT/scripts/schema-export/export-manifests.sql" >> "$TMP/login-manifests.sql"
PGPASSWORD="$TEST_EXPORT_PASSWORD" PGUSER=safe_export psql -X -v ON_ERROR_STOP=1 -f "$TMP/login-manifests.sql"
jq -e '.storage_buckets | any(.id == "synthetic" and .name == "Synthetic bucket")' "$TMP/login-manifests.json" >/dev/null
jq -e '.tables_and_columns | any(.schema == "storage" and .table == "objects" and .column == "name")' "$TMP/login-manifests.json" >/dev/null
jq -e '.policies | any(.name == "no_select_fixture_read")' "$TMP/login-manifests.json" >/dev/null

# PUBLIC grants on pg_catalog large-object functions bypass table ACL checks.
# Build the SECURITY DEFINER fixture before connecting as the restricted login.
psql -X -v ON_ERROR_STOP=1 <<'NETSQL'
CREATE SCHEMA net;
GRANT USAGE ON SCHEMA net TO PUBLIC;
CREATE TABLE net.request_queue(id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY, payload text NOT NULL);
CREATE FUNCTION net.http_post(text) RETURNS bigint
LANGUAGE sql SECURITY DEFINER
SET search_path = pg_catalog, net
AS 'INSERT INTO net.request_queue(payload) VALUES ($1) RETURNING id';
NETSQL

# Use ONE real safe_export login session for the default-setting override and all writes.
# ALTER ROLE ... SET is a connection default, not an enforced security boundary. SET changes
# the session default; a subsequent statement starts a writable transaction in this fixture.
SESSION_OUTPUT="$(PGPASSWORD="$TEST_EXPORT_PASSWORD" PGUSER=safe_export psql -X -q -v ON_ERROR_STOP=1 -At <<'SESSION_SQL'
SHOW default_transaction_read_only;
SET default_transaction_read_only = off;
SHOW default_transaction_read_only;
SELECT current_setting('transaction_read_only') = 'off';
SELECT bool_and(
  has_function_privilege(current_user, p.oid, 'EXECUTE')
  AND EXISTS (
    SELECT 1
    FROM aclexplode(coalesce(p.proacl, acldefault('f', p.proowner))) acl
    WHERE acl.grantee = 0 AND acl.privilege_type = 'EXECUTE'
  )
)
FROM pg_proc p
WHERE p.oid IN (
  'pg_catalog.lo_create(oid)'::regprocedure,
  'pg_catalog.lo_from_bytea(oid,bytea)'::regprocedure,
  'pg_catalog.lo_put(oid,bigint,bytea)'::regprocedure,
  'pg_catalog.lo_unlink(oid)'::regprocedure
);
SELECT has_function_privilege(current_user,p.oid,'EXECUTE')
  AND EXISTS (
    SELECT 1 FROM aclexplode(coalesce(p.proacl,acldefault('f',p.proowner))) acl
    WHERE acl.grantee=0 AND acl.privilege_type='EXECUTE'
  )
FROM pg_proc p WHERE p.oid='net.http_post(text)'::regprocedure;
DO $write_capability_test$
DECLARE created_oid oid;
BEGIN
  created_oid := pg_catalog.lo_create(0);
  PERFORM pg_catalog.lo_put(created_oid, 0, decode('4e4f56414149','hex'));
  PERFORM pg_catalog.lo_unlink(created_oid);
  created_oid := pg_catalog.lo_from_bytea(0, decode('4e4f56414149','hex'));
  PERFORM pg_catalog.lo_unlink(created_oid);
  PERFORM net.http_post('synthetic request');
END
$write_capability_test$;
SESSION_SQL
)"
printf '%s\n' "$SESSION_OUTPUT"
mapfile -t SESSION_RESULTS <<<"$SESSION_OUTPUT"
[[ "${SESSION_RESULTS[0]:-}" == "on" ]] || { echo "ERROR: restricted login did not start with default_transaction_read_only=on." >&2; exit 1; }
[[ "${SESSION_RESULTS[1]:-}" == "off" ]] || { echo "ERROR: restricted login could not change default_transaction_read_only to OFF in-session." >&2; exit 1; }
[[ "${SESSION_RESULTS[2]:-}" == "t" ]] || { echo "ERROR: next transaction did not become writable after the session override." >&2; exit 1; }
[[ "${SESSION_RESULTS[3]:-}" == "t" ]] || { echo "ERROR: expected PUBLIC-inherited EXECUTE on pg_catalog large-object functions was not reproduced." >&2; exit 1; }
[[ "${SESSION_RESULTS[4]:-}" == "t" ]] || { echo "ERROR: expected PUBLIC-inherited EXECUTE on synthetic SECURITY DEFINER routine was not reproduced." >&2; exit 1; }
psql -X -v ON_ERROR_STOP=1 -Atqc "SELECT count(*) FROM net.request_queue" | grep -qx 1
echo "SECURITY FINDING: safe_export can override its role's read-only connection default; PUBLIC large-object routines and a PUBLIC-executable SECURITY DEFINER routine both permit writes."

# Preflight must reject the synthetic user-defined SECURITY DEFINER routine by effective EXECUTE,
# while the PUBLIC-inherited pg_catalog large-object EXECUTE remains independently observable.
if PGPASSWORD="$TEST_EXPORT_PASSWORD" PGUSER=safe_export psql -X -v ON_ERROR_STOP=1 -f "$ROOT/scripts/schema-export/assert-read-only-role.sql" >"$TMP/queue-preflight.log" 2>&1; then
  echo "ERROR: preflight failed to reject synthetic PUBLIC-executable pg_net-style routine." >&2
  exit 1
fi
grep -Fq 'function ownership or EXECUTE on user-defined routines' "$TMP/queue-preflight.log" || {
  cat "$TMP/queue-preflight.log" >&2
  echo "ERROR: preflight rejected the queue fixture for an unexpected reason." >&2
  exit 1
}
echo "RESULT: preflight detects and rejects PUBLIC-inherited EXECUTE on the synthetic SECURITY DEFINER queue routine."

mkdir "$TMP/valid"
cp "$TMP/schema.sql" "$TMP/valid/schema.sql"
cp "$TMP/manifests.json" "$TMP/valid/manifests.json"
bash "$ROOT/scripts/schema-export/validate-export.sh" "$TMP/valid"
cp "$TMP/valid/schema.sql" "$TMP/valid/schema.original"
printf '
COPY public.products FROM stdin;
' >> "$TMP/valid/schema.sql"
if bash "$ROOT/scripts/schema-export/validate-export.sh" "$TMP/valid" >/dev/null 2>&1; then echo "ERROR: malicious COPY passed" >&2; exit 1; fi
mv "$TMP/valid/schema.original" "$TMP/valid/schema.sql"

age-keygen -o "$TMP/identity.txt" 2>"$TMP/age-keygen.log"
RECIPIENT="$(grep '^# public key:' "$TMP/identity.txt" | awk '{print $4}')"
[[ "$RECIPIENT" == age1* ]]
printf 'synthetic-schema-fixture
' > "$TMP/plain.txt"
sha256sum "$TMP/plain.txt" > "$TMP/plain.SHA256"
age -r "$RECIPIENT" -o "$TMP/plain.txt.age" "$TMP/plain.txt"
age -d -i "$TMP/identity.txt" -o "$TMP/decrypted.txt" "$TMP/plain.txt.age"
cmp "$TMP/plain.txt" "$TMP/decrypted.txt"
(cd "$TMP" && sha256sum -c plain.SHA256)
if env -u SUPABASE_DB_URL bash -c 'set -u; : "${SUPABASE_DB_URL:?missing database credential}"' >/dev/null 2>&1; then exit 1; fi
if age -r 'not-an-age-recipient' -o "$TMP/invalid.age" "$TMP/plain.txt" >/dev/null 2>&1; then exit 1; fi
FAILDIR="$TMP/failure-workspace"
mkdir -p -m 700 "$FAILDIR/plain"
printf 'synthetic plaintext' > "$FAILDIR/plain/plain.sql"
( trap 'rm -rf "$FAILDIR/plain"' EXIT; false ) || true
[[ ! -e "$FAILDIR/plain" ]]
UPLOAD_BLOCK="$(sed -n '/name: Upload ciphertext and ciphertext checksum only/,+12p' "$ROOT/.github/workflows/production-schema-export.yml")"
grep -Fq 'novaai-production-schema.tar.gz.age' <<<"$UPLOAD_BLOCK"
grep -Fq 'SHA256SUMS' <<<"$UPLOAD_BLOCK"
! grep -Eq 'schema\.sql|manifests\.json|export\.tar\.gz' <<<"$UPLOAD_BLOCK"
UPLOAD_PATHS="$(sed -n '/path: |/,+4p' "$ROOT/.github/workflows/production-schema-export.yml" | grep -E 'novaai-production-schema\.tar\.gz\.age|SHA256SUMS' || true)"
[[ "$(printf '%s
' "$UPLOAD_PATHS" | sed '/^$/d' | wc -l)" -eq 2 ]]
! grep -Eiq '\.(sql|json|tar|gz)$' <<<"$UPLOAD_PATHS"
echo "Isolated schema-export tests passed."
