#!/usr/bin/env bash
set -Eeuo pipefail
export PGHOST="${PGHOST:-postgres}" PGPORT="${PGPORT:-5432}" PGUSER="${PGUSER:-postgres}" PGPASSWORD="${PGPASSWORD:-postgres}" PGDATABASE="${PGDATABASE:-postgres}"
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
TMP="$(mktemp -d)"
cleanup(){ rm -rf "$TMP"; }
trap cleanup EXIT

psql -X -v ON_ERROR_STOP=1 <<'SQL'
CREATE ROLE safe_export LOGIN;
CREATE ROLE inherited_writer NOLOGIN;
CREATE ROLE member_export LOGIN;
CREATE ROLE direct_writer LOGIN;
CREATE SCHEMA private;
CREATE SCHEMA storage;
CREATE TABLE public.products(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name text NOT NULL);
CREATE TABLE public."Products"(id bigint PRIMARY KEY, label text);
CREATE TABLE private.internal_config(id integer PRIMARY KEY, value text);
CREATE TABLE storage.buckets(id text PRIMARY KEY, name text NOT NULL, public boolean NOT NULL DEFAULT false, file_size_limit bigint, allowed_mime_types text[]);
CREATE TABLE storage.objects(id uuid PRIMARY KEY, bucket_id text, name text);
CREATE SEQUENCE public.synthetic_seq;
CREATE FUNCTION public.safe_constant() RETURNS integer LANGUAGE sql IMMUTABLE AS 'SELECT 7';
REVOKE ALL ON FUNCTION public.safe_constant() FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.safe_constant() TO safe_export;
CREATE FUNCTION public.unsafe_change() RETURNS void LANGUAGE plpgsql VOLATILE AS $ BEGIN INSERT INTO public.products(name) VALUES ('forbidden'); END $;
REVOKE ALL ON FUNCTION public.unsafe_change() FROM PUBLIC;
ALTER TABLE public.products ENABLE ROW LEVEL SECURITY;
CREATE POLICY products_read ON public.products FOR SELECT TO safe_export USING (true);
INSERT INTO storage.buckets(id,name) VALUES ('synthetic','Synthetic bucket');
GRANT USAGE ON SCHEMA public,private,storage TO safe_export;
GRANT SELECT ON public.products,public."Products",private.internal_config,storage.buckets TO safe_export;
GRANT inherited_writer TO member_export;
GRANT SELECT ON public.products TO member_export;
GRANT INSERT ON public.products TO inherited_writer;
GRANT USAGE ON SCHEMA public TO inherited_writer;
GRANT INSERT ON public.products TO direct_writer;
GRANT USAGE ON SCHEMA public TO direct_writer;
SQL

psql -X -v ON_ERROR_STOP=1 -f "$ROOT/scripts/schema-export/export-manifests.sql" -o "$TMP/manifests.json"
jq -e '.product_case_check.lower_exists and .product_case_check.upper_exists and .product_case_check.distinct' "$TMP/manifests.json" >/dev/null
jq -e '.policies | any(.name == "products_read")' "$TMP/manifests.json" >/dev/null
jq -e '.sequences | any(.name == "synthetic_seq")' "$TMP/manifests.json" >/dev/null
jq -e '.functions | any(.name == "safe_constant") and any(.name == "unsafe_change")' "$TMP/manifests.json" >/dev/null
jq -e '.role_memberships | any(.member == "member_export" and .role == "inherited_writer")' "$TMP/manifests.json" >/dev/null
jq -e '.table_grants | any(.grantee == "direct_writer" and .privilege == "INSERT")' "$TMP/manifests.json" >/dev/null
psql -X -v ON_ERROR_STOP=1 -c 'SET ROLE safe_export' -f "$ROOT/scripts/schema-export/assert-read-only-role.sql" >/dev/null
if psql -X -v ON_ERROR_STOP=1 -c 'SET ROLE direct_writer' -f "$ROOT/scripts/schema-export/assert-read-only-role.sql" >/dev/null 2>&1; then echo "ERROR: direct writer passed" >&2; exit 1; fi
if psql -X -v ON_ERROR_STOP=1 -c 'SET ROLE member_export' -f "$ROOT/scripts/schema-export/assert-read-only-role.sql" >/dev/null 2>&1; then echo "ERROR: inherited writer passed" >&2; exit 1; fi

pg_dump --schema-only --schema=public --schema=private "$PGDATABASE" > "$TMP/schema.sql"
mkdir "$TMP/valid"
cp "$TMP/schema.sql" "$TMP/valid/schema.sql"
cp "$TMP/manifests.json" "$TMP/valid/manifests.json"
bash "$ROOT/scripts/schema-export/validate-export.sh" "$TMP/valid"
cp "$TMP/valid/schema.sql" "$TMP/valid/schema.original"
printf '\nCOPY public.products FROM stdin;\n' >> "$TMP/valid/schema.sql"
if bash "$ROOT/scripts/schema-export/validate-export.sh" "$TMP/valid" >/dev/null 2>&1; then echo "ERROR: malicious COPY passed" >&2; exit 1; fi
mv "$TMP/valid/schema.original" "$TMP/valid/schema.sql"

age-keygen -o "$TMP/identity.txt" 2>"$TMP/age-keygen.log"
RECIPIENT="$(grep '^# public key:' "$TMP/age-keygen.log" | awk '{print $4}')"
[[ "$RECIPIENT" == age1* ]]
printf 'synthetic-schema-fixture\n' > "$TMP/plain.txt"
sha256sum "$TMP/plain.txt" > "$TMP/plain.SHA256"
age -r "$RECIPIENT" -o "$TMP/plain.txt.age" "$TMP/plain.txt"
age -d -i "$TMP/identity.txt" -o "$TMP/decrypted.txt" "$TMP/plain.txt.age"
cmp "$TMP/plain.txt" "$TMP/decrypted.txt"
(cd "$TMP" && sha256sum -c plain.SHA256)
if env -u SUPABASE_DB_URL bash -c 'set -u; : "${SUPABASE_DB_URL:?missing database credential}"' >/dev/null 2>&1; then exit 1; fi
if age -r 'not-an-age-recipient' -o "$TMP/invalid.age" "$TMP/plain.txt" >/dev/null 2>&1; then exit 1; fi
FAILDIR="$TMP/failure-workspace"
mkdir -m 700 "$FAILDIR/plain"
printf 'synthetic plaintext' > "$FAILDIR/plain/plain.sql"
( trap 'rm -rf "$FAILDIR/plain"' EXIT; false ) || true
[[ ! -e "$FAILDIR/plain" ]]
UPLOAD_PATHS=$'encrypted.age\nSHA256SUMS'
[[ "$(printf '%s\n' "$UPLOAD_PATHS" | wc -l)" -eq 2 ]]
! grep -Eiq '\.(sql|json|tar|gz)$' <<<"$UPLOAD_PATHS"
echo "Isolated schema-export tests passed."
